// Host-only syscall/ownership tests. Invocation is a mock, NEVER native ARM64 evidence.
#define _GNU_SOURCE
#include <assert.h>
#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>

static unsigned acquisitions, releases, protections, invocations, live;
static unsigned fail_acquire, fail_protect, fail_release;
static int saw_rx;
static const void *published_source;
static struct { void *base; size_t span; int prot; } allocations[2];

static void *checked_mmap(void *address, size_t size, int prot, int flags, int fd, off_t offset)
{
    ++acquisitions;
    if (acquisitions == fail_acquire) { errno = ENOMEM; return MAP_FAILED; }
    assert(address == NULL && prot == PROT_NONE);
    assert(size == 3 * 4096 || size == 3 * 16384);
    assert(flags == (MAP_PRIVATE | MAP_ANONYMOUS) && fd == -1 && offset == 0);
    void *allocation = NULL;
    // Owned, zeroed host memory only. Permissions are recorded, not applied:
    // simulate either geometry independently of the host kernel's page size.
    assert(posix_memalign(&allocation, 16384, size) == 0);
    memset(allocation, 0, size);
    unsigned slot = allocations[0].base == NULL ? 0 : 1;
    assert(allocations[slot].base == NULL);
    allocations[slot].base = allocation;
    allocations[slot].span = size;
    ++live;
    return allocation;
}

static int checked_mprotect(void *address, size_t size, int prot)
{
    ++protections;
    assert(size == 4096 || size == 16384);
    assert((uintptr_t)address % size == 0);
    unsigned slot;
    for (slot = 0; slot < 2; ++slot) {
        if (allocations[slot].base != NULL &&
            address == (unsigned char *)allocations[slot].base + size &&
            allocations[slot].span == 3 * size) break;
    }
    assert(slot < 2); // Exact owned middle page, never a guard or an out-of-bounds range.
    assert(prot == (protections == 3 ? (PROT_READ | PROT_EXEC) : (PROT_READ | PROT_WRITE)));
    if (protections == fail_protect) { errno = EACCES; return -1; }
    if (prot == (PROT_READ | PROT_EXEC)) saw_rx = 1;
    allocations[slot].prot = prot;
    return 0;
}

static int checked_munmap(void *address, size_t size)
{
    ++releases;
    if (releases == fail_release) { errno = EIO; return -1; }
    assert(size == 3 * 4096 || size == 3 * 16384);
    assert(live > 0);
    unsigned slot = allocations[0].base == address ? 0 : 1;
    assert(allocations[slot].base == address && allocations[slot].span == size);
    allocations[slot].base = NULL;
    free(address);
    --live;
    return 0;
}

static void *observed_memcpy(void *destination, const void *source, size_t size)
{
    if (allocations[1].base != NULL &&
        destination == (unsigned char *)allocations[1].base + allocations[1].span / 3) {
        assert(size == 36);
        published_source = source;
    }
    return memcpy(destination, source, size);
}

#define RVZR_ARCH_HOST_TEST
#define mmap checked_mmap
#define mprotect checked_mprotect
#define munmap checked_munmap
#define memcpy observed_memcpy
#include "../../tools/arm64_architectural_smoke.c"
#undef mmap
#undef mprotect
#undef munmap
#undef memcpy

// Generated by the test wrapper from the actual GNU-assembled reference, never executed here.
#include <rvzr_fixture_reference.h>
static const input_t *expected_input;
static const unsigned char *expected_program;
void rvzr_arch_invoke(void *code, void *main, uint64_t selector, arch_state_t *state)
{
    (void)state;
    assert(saw_rx && live == 2);
    assert(main == (unsigned char *)allocations[0].base + allocations[0].span / 3);
    assert(code == (unsigned char *)allocations[1].base + allocations[1].span / 3);
    assert(allocations[0].prot == (PROT_READ | PROT_WRITE));
    assert(allocations[1].prot == (PROT_READ | PROT_EXEC));
    assert(expected_input != NULL);
    assert(memcmp(main, expected_input->bytes, MAIN_BYTES) == 0);
    assert(selector == read_le64(expected_input->bytes + SELECTOR_OFFSET));
    assert(expected_program != NULL && published_source == expected_program);
    assert(memcmp(code, expected_program, FIXTURE_BYTES) == 0);
    ++invocations;
}

int main(int argc, char **argv)
{
    assert(argc >= 2);
    if (strcmp(argv[1], "admission") == 0) {
        int error = runner_main(argc - 1, argv + 1); // Actual admission, not an imitation.
        assert(error != 0 && acquisitions == 0 && invocations == 0);
        return error;
    }
    assert(argc == 2);
    if (strcmp(argv[1], "decode") == 0 || strcmp(argv[1], "decode-program") == 0 ||
        strcmp(argv[1], "decode-family") == 0) {
        input_t input;
        unsigned char program[FIXTURE_BYTES];
        memset(program, 0xa5, sizeof(program));
        memset(&input, 0xa5, sizeof(input));
        int generated = strcmp(argv[1], "decode") != 0;
        program_policy_t policy = strcmp(argv[1], "decode-family") == 0
            ? MOVZ16_FAMILY : EXACT_PROGRAM;
        int error = generated ? read_program_input(STDIN_FILENO, program, &input, policy)
                              : read_input(STDIN_FILENO, &input);
        if (error != 0) {
            // Validation failures do not publish partially filled input state.
            for (size_t i = 0; i < sizeof(input.bytes); ++i) assert(input.bytes[i] == 0xa5);
            for (size_t i = 0; i < sizeof(program); ++i) assert(program[i] == 0xa5);
            assert(acquisitions == 0 && invocations == 0);
            return failure("input", errno, 0, 0, 0);
        }
        assert(acquisitions == 0 && invocations == 0);
        printf("{\"kind\":\"%s\",\"selector\":%" PRIu64 ",", generated ? "decoded_program" : "decoded_input",
               read_le64(input.bytes + SELECTOR_OFFSET));
        if (generated) {
            printf("\"program_hex\":\"");
            for (size_t i = 0; i < sizeof(program); ++i) printf("%02x", program[i]);
            printf("\",");
        }
        printf("\"main_hex\":\"");
        for (size_t i = 0; i < MAIN_BYTES; ++i) printf("%02x", input.bytes[i]);
        puts("\"}");
        return 0;
    }
    unsigned scenario = (unsigned)strtoul(argv[1], NULL, 10);
    size_t span = 0;
    assert(region_span(4096, 36, &span) == 0 && span == 12288);
    assert(region_span(16384, 4096, &span) == 0 && span == 49152);
    assert(region_span(4096, 4097, &span) == -1);
    assert(region_span(16384, 16385, &span) == -1);
    assert(region_span(4096, 0, &span) == -1);
    assert(region_span(8192, 36, &span) == -1);
    assert(region_span(SIZE_MAX, 36, &span) == -1);
    if (scenario == 16) {
        result_t result = {0};
        input_t input = {0};
        unsigned char invalid[FIXTURE_BYTES];
        memcpy(invalid, rvzr_fixture, sizeof(invalid));
        invalid[0] ^= 1;
        assert(execute_fixed(&result, 4096, &input, invalid, EXACT_PROGRAM) != 0);
        assert(execute_fixed(&result, 4096, &input, invalid, MOVZ16_FAMILY) != 0);
        assert(result.error == ENOTSUP && acquisitions == 0 && invocations == 0 && live == 0);
    } else if (scenario == 9 || scenario == 10) {
        pid_t child = fork();
        assert(child >= 0);
        if (child == 0) {
            if (scenario == 9) _exit(7);
            for (;;) pause(); // No fixture invocation; parent must bound and reap this child.
        }
        int status = 0, timed_out = 0;
        assert(wait_bounded(child, &status, &timed_out) == 0);
        assert(timed_out == (scenario == 10));
        if (scenario == 9) assert(WIFEXITED(status) && WEXITSTATUS(status) == 7);
        else assert(WIFSIGNALED(status) && WTERMSIG(status) == SIGKILL);
        assert(waitpid(child, &status, WNOHANG) == -1 && errno == ECHILD);
    } else if (scenario == 11) {
        return failure("host_mock", EACCES, SIGTERM, 1, -1);
    } else if (scenario == 7) {
        region_t region = {0};
        assert(region_open(&region, 4096, 4096) == 0);
        assert(region_open(&region, 4096, 4096) == -1 && acquisitions == 1);
        fail_release = 1;
        assert(region_close(&region) == -1 && region.reservation != NULL && live == 1);
        fail_release = 0;
        assert(region_close(&region) == 0 && region.reservation == NULL && live == 0);
        assert(region_close(&region) == 0 && releases == 2); // idempotent cleanup
    } else {
        if (scenario == 1 || scenario == 2) fail_acquire = scenario;
        if (scenario >= 3 && scenario <= 5) fail_protect = scenario - 2;
        if (scenario == 6) fail_release = 1;
        result_t result = {0};
        input_t input = {0};
        input.bytes[0] = 7;
        if (scenario == 12 || scenario == 13) {
            for (size_t i = 0; i < MAIN_BYTES; ++i) input.bytes[i] = (unsigned char)(i * 17);
            input.bytes[SELECTOR_OFFSET + 7] = 0x80;
        }
        expected_input = &input;
        unsigned char received[FIXTURE_BYTES];
        memcpy(received, rvzr_fixture, sizeof(received));
        if (scenario == 17 || scenario == 18) {
            // MOVZ X1,#0 / MOVZ X1,#65535. Source and RX bytes must be this snapshot.
            const unsigned char first[] = {1, 0, 0x80, 0xd2};
            const unsigned char second[] = {0xe1, 0xff, 0x9f, 0xd2};
            memcpy(received + 8, first, 4);
            memcpy(received + 16, second, 4);
        }
        expected_program = scenario >= 14 ? received : rvzr_fixture;
        size_t page = scenario == 8 || scenario == 13 || scenario == 15 || scenario == 18
            ? 16384 : 4096;
        int error = execute_fixed(&result, page, &input, expected_program,
                                 scenario >= 17 ? MOVZ16_FAMILY : EXACT_PROGRAM);
        int success = scenario == 0 || scenario == 8 || scenario >= 12;
        assert(error == (success ? 0 : 1));
        assert(invocations == ((success || scenario == 6) ? 1U : 0U));
        assert(result.stage == COMPLETE || result.error != 0);
        assert(live == (scenario == 6 ? 1U : 0U));
        if (success) assert(memcmp(result.main, input.bytes, MAIN_BYTES) == 0);
        if (scenario == 6) {
            assert(releases == 2 && result.stage == CLEANUP);
            // Verify retained mock ownership, then reclaim host test memory. For
            // production mmap reservations, child exit is the final backstop.
            for (unsigned slot = 0; slot < 2; ++slot) free(allocations[slot].base);
        }
    }
    printf("host-only geometry/cleanup scenario %u passed\n", scenario);
    return 0;
}
